package io.github.zapretkvn.android.vpn

/**
 * Состояние пути поверх «Подключено». Единственный владелец — надзор за путём в
 * акторе VPN (ServerSwitchCoordinator); контроллер только публикует значение для
 * экрана. Пока путь проверяется или сервер меняется, экран не может показать
 * «Всё работает».
 */
enum class PathStatus {
    /** Путь подтверждён или сигналов беды нет. */
    Ok,

    /** Пассивный сигнал (данные перестали идти): идёт одна проверка текущего сервера. */
    Checking,

    /** Сервер меняется: переключение с проверкой кандидата. */
    Switching,

    /** Сервер не отвечает, замены нет. */
    Lost,
}
